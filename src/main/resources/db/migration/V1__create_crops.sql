CREATE TABLE crops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    variety VARCHAR(100),
    season VARCHAR(20) NOT NULL,
    soil_type VARCHAR(100),
    expected_yield_kg_per_hectare NUMERIC(10, 2),
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_crops_expected_yield_positive
        CHECK (expected_yield_kg_per_hectare IS NULL OR expected_yield_kg_per_hectare > 0),
    CONSTRAINT chk_crops_season
        CHECK (season IN ('KHARIF', 'RABI', 'ZAID', 'PERENNIAL'))
);

CREATE INDEX idx_crops_name ON crops (name);
